#!/usr/bin/env python3
# dxe3res for hosts without one: list the symbols a DXE3 module imports and
# write the dlregsym() table the host program must provide for them.
#
#   dxe3res.py [-o table.c] [-n name] module.dxe ...
#
# The table self-registers (DXE_EXPORT_TABLE_AUTO), so the host only has to
# compile the file into its link; every listed symbol is pulled from the
# host's libraries by the reference in the table. Without -o the symbol names
# are printed one per line.

import argparse
import struct
import sys

DXE_MAGIC = 0x31455844
HEADER = '<4lLbbh14l'   # dxe3_header in <sys/dxe.h>


def unresolved(path):
    data = open(path, 'rb').read()
    fields = struct.unpack_from(HEADER, data, 0)
    magic, hdr_size, n_unres, unres_table = fields[0], fields[4], fields[15], fields[16]
    if magic != DXE_MAGIC or hdr_size < struct.calcsize(HEADER):
        sys.exit(f'{path}: not a DXE3 module')
    names = []
    pos = unres_table
    for _ in range(n_unres):
        rel, absolute = struct.unpack_from('<HH', data, pos)
        pos += 4
        end = data.index(b'\0', pos)
        names.append(data[pos:end].decode())
        pos = end + 1 + 4 * (rel + absolute)
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-o', dest='output', help='write a C symbol table instead of the list')
    ap.add_argument('-n', dest='name', default='dxe_import_table', help='table name (default dxe_import_table)')
    ap.add_argument('modules', nargs='+')
    args = ap.parse_args()

    names = sorted({n for m in args.modules for n in unresolved(m)})

    if not args.output:
        print('\n'.join(names))
        return

    with open(args.output, 'w') as out:
        out.write('/* Generated by dxe3res.py from %s: the symbols the module imports,\n'
                  '   exported to it by the host through dlregsym(). Do not edit. */\n'
                  '#include <sys/dxe.h>\n\n' % ' '.join(args.modules))
        for n in names:
            out.write('extern_asm(%s);\n' % n)
        out.write('\nDXE_EXPORT_TABLE_AUTO (%s)\n' % args.name)
        for n in names:
            out.write('  DXE_EXPORT_ASM (%s)\n' % n)
        out.write('DXE_EXPORT_END\n')


if __name__ == '__main__':
    main()
